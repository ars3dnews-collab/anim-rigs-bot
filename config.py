# ---------------------------------------------------------------------------
# Ритм публикаций.
#
# На расписание GitHub полагаться нельзя: он массово пропускает
# срабатывания и по факту запускает задание раз в 1-5 часов, хотя в cron
# стоит каждые 20 минут. Поэтому ритм держит сам бот: он смотрит, сколько
# прошло с прошлого поста, и публикует при первом же запуске, который
# случился после нужного момента. Частый cron — это не расписание постов,
# а просто побольше попыток, чтобы слот не пропал.
# ---------------------------------------------------------------------------

# Шаг между постами: раз в два часа.
POST_EVERY_MINUTES = 120

# Допуск: публикуем, если с прошлого поста прошло хотя бы столько минут.
# Ставится чуть меньше шага, потому что GitHub запускает задание не
# секунда в секунду: без допуска каждый второй слот пропускался бы
# из-за опоздания на пару минут.
MIN_GAP_MINUTES = 105

# ---------------------------------------------------------------------------
# Часовой пояс канала и часы тишины.
#
# Ночью посты не выходят. Расписание GitHub живёт по UTC, поэтому бот
# сам пересчитывает время в местное и решает, спать ему или публиковать.
# ---------------------------------------------------------------------------

# Смещение местного времени от UTC, часов. 5 — Екатеринбург.
UTC_OFFSET_HOURS = 5

# Часы, когда посты разрешены: с 8 утра до 23:00 по местному времени.
# Восемь слотов с шагом в два часа: 8, 10, 12, 14, 16, 18, 20, 22.
ACTIVE_HOURS = (8, 23)

# 0 — запуск публикует и сразу выходит (как у бота новостей GTA 6).
# Длинные запуски GitHub душит: пока одно задание висит час, все
# срабатывания расписания в это время отбрасываются.
LOOP_MINUTES = 0

# Сколько постов за один запуск
MAX_POSTS_PER_RUN = 1

# Пауза между постами внутри одного запуска, секунд (для ручного режима)
