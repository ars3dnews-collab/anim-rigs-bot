"""Настройки бота. Правится прямо в репозитории — Actions подхватит при следующем запуске."""

# ---------------------------------------------------------------------------
# Ритм публикаций.
#
# GitHub не умеет надёжно запускать задания раз в 10 минут: короткие
# расписания он массово пропускает. Поэтому расписание стоит РАЗ В ЧАС,
# а десятиминутный шаг бот отсчитывает сам внутри одного запуска.
# Один запуск живёт LOOP_MINUTES и публикует пост каждые POST_EVERY_MINUTES.
# ---------------------------------------------------------------------------

# Шаг между постами, минут
POST_EVERY_MINUTES = 10

# Сколько минут работает один запуск. Должно быть меньше 60, чтобы
# закончиться до следующего срабатывания по расписанию.
# Потолок GitHub на одно задание — 6 часов, так что запас большой.
LOOP_MINUTES = 55

# Предохранитель: больше этого за один запуск не опубликуем ни при каких
# обстоятельствах, даже если что-то пойдёт не так с таймингом.
MAX_POSTS_PER_RUN = 8

# Пауза между постами внутри одного запуска, секунд (для ручного режима)
DELAY_BETWEEN_POSTS = 5

# Таймаут одного HTTP-запроса, секунд. Highend3d временами тупит,
# и без этого один медленный сайт вешает весь запуск.
HTTP_TIMEOUT = 12

# Сколько секунд всего отводится на обход источников. Как только время
# вышло, бот перестаёт ходить по сайтам и публикует из того, что успел.
